#include <iostream>

using namespace std;

int field[35][35];
const int MUSHROOM = -1;

int main() {
    int n, m, w;
    cin >> n >> m >> w;

    // Считываем грибы
    for (int i = 0; i < w; i++) {
        int r, c;
        cin >> r >> c;
        field[r - 1][c - 1] = MUSHROOM;
    }

    // Массивы сдвигов для 8 соседей
    // dr[] — это сдвиг по вертикали (строки), dc[] — по горизонтали (столбцы).
    // Они работают парами по общему индексу: например, dr[0] и dc[0] равны -1 и -1,
    // что соответствует направлению «вверх-влево» от текущей клетки.
    int dr[] = {-1, -1, -1, 0, 0, 1, 1, 1};
    int dc[] = {-1, 0, 1, -1, 1, -1, 0, 1};

    // Перебираем все клетки поля по строкам (r) и столбцам (c)
    for (int r = 0; r < n; r++) {
        for (int c = 0; c < m; c++) {
            if (field[r][c] == MUSHROOM) {
                cout << '*';
            } else {
                int count = 0;
                // Цикл от 0 до 7 последовательно перебирает все 8 направлений из массивов сдвигов
                for (int i = 0; i < 8; i++) {
                    int nr = r + dr[i];// Новая строка соседа
                    int nc = c + dc[i];// Новый столбец соседа

                    // проверяем, что соседняя клетка
                    // находится внутри границ поля и мы не вылетели за массив.
                    // field[nr][nc] == MUSHROOM — проверяем, лежит ли в соседней клетке гриб.
                    if (nr >= 0 && nr < n && nc >= 0 && nc < m && field[nr][nc] == MUSHROOM) {
                        count++;
                    }
                }
                cout << count;
            }
        }
        cout << endl;
    }
    return 0;
}
